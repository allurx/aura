export const HANDBOOK_VERSION = 6;

// 手册与普通 TXT 共用章节解析，章标题需保持可识别的“第 N 章”形式。
const handbookText = `
第一章 快速开始
Aura 是一个离线优先的 TXT 阅读器，不需要账户。导入一本书，找一个舒服的姿势，就可以开始阅读。

1. 返回书架，点击顶部“导入 TXT”，选择一本或多本 .txt 文件。窄屏上导入按钮可能只显示 +。
2. 等待当前文件的处理状态结束。导入成功会短暂提示；未导入的文件可展开查看原因。
3. 点击书封进入阅读。手机上上下滑动正文阅读，轻点正文中间区域可显示或收起阅读工具。

Aura 自动识别 UTF-8、GB18030、Big5 和带 BOM 的 UTF-16。遇到编码提示时，用文本编辑器将原文件另存为 UTF-8 后重试；只改扩展名不能转换编码。
同一内容可以重复导入，每本书分别保存进度。批次中断时，已经成功导入的书籍会保留。

第二章 查找整理
桌面从左侧选择分类；手机点击书架左上角菜单打开导航。顶部搜索框只搜索当前分类，想找整个书架中的书，请先选择“全部书籍”。

在具体分类内导入会归入该分类；在“全部书籍”中导入会归入“收藏”。选择书目下方的分类即可移动书籍，阅读进度会保留。

删除按钮会先确认书名，再删除该书及其进度。导航底部“清空书架”会在确认后删除所有分类中的书籍与进度。请保留原始 TXT 文件，方便需要时重新导入。

第三章 阅读接续
桌面阅读器的左上角返回书架，右上角打开目录，左下角调整外观，右下角切换全屏。全屏能否使用取决于浏览器和当前打开环境。

手机或触摸设备进入阅读后，默认隐藏上下工具栏。上下滑动正文阅读，轻点正文中间区域唤出工具：顶部显示书名，底部从左到右是“书架、目录、外观、全屏”。再次轻点中间区域即可收起；切换章节后也会回到沉浸阅读。
使用键盘时，可用 Tab 找到“显示阅读工具”入口；工具显示时，Escape 也可收起。滑动阅读和长按选择文字不会开关工具栏。

打开“目录”后可按章节名称搜索，也可用“定位当前章节”回到正在读的章。轻点章名即可跳转；不想切换时，点击关闭按钮返回正文，键盘也可按 Escape 关闭。

章末提供“上一章”和“下一章”；键盘操作时，正文获得焦点后可用左右方向键切章。手机通过章末按钮或目录切章。

阅读位置会自动保存。再次打开同一本书会接续上次的位置；返回书架时，会恢复当前分类、搜索和列表位置。

第四章 主题与外观
书架的“外观”在顶部，手机书架上可能只显示设置图标。桌面阅读器的“外观”在左下角；手机或触摸设备先轻点正文中间区域，再点击底部“外观”打开面板。

默认主题是“晴空”。你也可以选择浅色的“海盐”“薄荷”“杏桃”“花信”“纸页”，或深色的“星夜”“暮色”“深海”。在同一面板内选择具体区域，还能调整字号、文字颜色、背景颜色和留白；正文可调整行距，桌面可调整阅读宽度。

拖动滑块时可实时预览，松开后保存；颜色选择完成后保存。关闭面板会取消尚未提交的预览。你手动指定的区域颜色优先于主题，切换主题不会清除这些设置。

书架与阅读器的外观分别保存。“重置当前页面”只恢复当前页面的默认外观，不影响另一页，也不会删除书籍或进度。

第五章 本地与离线
导入的文本与阅读进度保存在当前浏览器的本地数据库中，不会上传。外观也保存在当前浏览器中。不同浏览器、设备或访问地址之间不会自动同步。

需要不联网打开时，使用 portable 单文件 HTML，直接用浏览器打开即可。它包含应用本身，不包含已经导入的书籍或阅读进度；换设备时，请带上 TXT 文件并重新导入。

浏览器清理、清除网站数据或存储空间不足可能让本地数据不可用。移动或重命名 portable HTML 后，也不应假定仍能访问原书架。保留 TXT 原文件是最直接的备份方式。

第六章 帮助交流
书架导航底部的“阅读帮助”可再次打开本手册。手机先打开左上角菜单即可找到。阅读手册时，可从“目录”直接选择以上六章。

欢迎加入 Aura QQ 交流群：1038423789
遇到问题时，可以说明浏览器、设备、操作步骤和看到的提示；涉及书籍内容时，不必发送整本书或私人文本。
`.trim();

/**
 * 创建内置 Aura 手册文件。
 * @returns 内置手册文件
 */
export function createHandbookFile(): File {
    return new File([handbookText], "Aura.txt", { type: "text/plain" });
}
